import torch
import json
import argparse
import os
import requests


def _extract_json_object(text: str) -> dict:
    s = text.strip()
    if s.startswith("```json"):
        s = s[7:]
        if s.endswith("```"):
            s = s[:-3]
    elif s.startswith("```") and s.endswith("```"):
        s = s[3:-3]
    s = s.strip()

    try:
        return json.loads(s)
    except Exception:
        pass

    start = s.find("{")
    end = s.rfind("}")
    if start != -1 and end != -1 and end > start:
        return json.loads(s[start : end + 1])

    raise ValueError("No JSON object found in model response")

def get_top_k_activating_contexts(f_acts_path: str, dataset_text_path: str, feature_indices: list, top_n: int = 10):
    """
    Simulates aligning activations to the original dataset tokens to extract max-activating
    examples for targeted features.
    
    Since extracting actual string shards from dataloaders mapping back to tokens is complex
    and requires tracking token offsets, this provides the skeleton logic. 
    It loads the specific sparse activations, finds the highest magnitudes, 
    and constructs the context dictionaries for the LLM judge.
    """
    print(f"Loading sparse acts from {f_acts_path}")
    activations = torch.load(f_acts_path)
    
    # Normally we load the matching dataset here to index the exact strings. 
    contexts = {int(feature_idx): [] for feature_idx in feature_indices}
    
    for feat_idx in feature_indices:
        feat_vector = activations[:, feat_idx]
        
        # Get top-N values and their token indices
        top_vals, top_indices = torch.topk(feat_vector, top_n)
        
        for val, idx in zip(top_vals, top_indices):
            # In a full run, we index the dataset here using `idx`
            # For skeleton, we mock the string retrieval
            mock_string_context = f"[Mock context from dataset index {idx.item()} with activation {val.item():.2f}]"
            contexts[int(feat_idx)].append({
                "activation": val.item(),
                "context": mock_string_context
            })
            
    return contexts

def build_llm_prompt(feature_idx: int, top_contexts: list):
    """Constructs the prompt for the Frontier LLM to auto-annotate the feature."""
    prompt = f"""You are an expert interpretability researcher analyzing a specific 'feature' direction isolated from a neural network's activations. 
This feature activates exactly when a specific concept, pattern, or semantic meaning is present in the text.

Below are the text snippets that caused this feature to activate the most (Top-{len(top_contexts)}). The text that caused the activation is enclosed in [ACT]...[/ACT].

"""
    for i, ctx in enumerate(top_contexts):
        prompt += f"Example {i+1} (Activation Strength: {ctx['activation']:.2f}):\n{ctx['context']}\n\n"
        
    prompt += """Analyze the examples and perform the following tasks:
1. Identify the single unifying concept or pattern that causes this feature to fire.
2. Provide a short, 1-5 word label for this feature.
3. Assign a confidence score from 0.0 (incoherent noise/hallucination) to 1.0 (crystal clear monosemantic feature).

Return ONLY a JSON object with the keys "concept", "label", and "confidence".
"""
    return prompt

def test_illusion_of_interpretability(feature_dict_report: str, f_acts_path: str, data_path: str, out_file: str, local_api_base: str = None, local_model_id: str = None):
    """
    The main Auto-Annotator Pipeline testing for the Illusion of Interpretability.
    
    It pulls the 'Domain Specific' candidate features generated by the MP bulk algorithm,
    extracts their top contexts, sends them to the LLM for grading, and flags potential
    illusions (high variance but low LLM confidence).
    """
    with open(feature_dict_report, 'r') as f:
        report = json.load(f)
        
    domain_candidates = report['Categories']['domain']
    
    # We sample a subset (e.g. 50) if the list is huge to save API costs
    test_subset = domain_candidates[:50]
    
    print(f"Testing {len(test_subset)} Domain-Specific MP features using Auto-Annotator...")

    if len(test_subset) == 0:
        print("No domain-specific MP features found; writing empty annotation report.")
        os.makedirs(os.path.dirname(out_file), exist_ok=True)
        with open(out_file, 'w') as f:
            json.dump({}, f, indent=4)
        print(f"LLM Annotations saved to {out_file}")
        return
    
    top_contexts = get_top_k_activating_contexts(f_acts_path, data_path, test_subset, top_n=10)
    
    results = {}
    for feat_idx in test_subset:
        contexts = top_contexts[int(feat_idx)]
        prompt = build_llm_prompt(feat_idx, contexts)
        
        # Here is where the actual API call to OpenAI occurs.
        print(f"Evaluating Feature {feat_idx}...")
        
        api_key = os.environ.get("OPENAI_API_KEY", "EMPTY")
        if api_key != "EMPTY" or local_api_base:
            try:
                if local_api_base:
                    model_to_use = local_model_id if local_model_id else "meta-llama/Meta-Llama-3-70B-Instruct"
                    # Direct HTTP request to vLLM API
                    url = f"{local_api_base}/chat/completions"
                    payload = {
                        "model": model_to_use,
                        "messages": [{"role": "user", "content": prompt}],
                        "temperature": 0.0,
                        "max_tokens": 256
                    }
                    response = requests.post(url, json=payload, timeout=30)
                    response.raise_for_status()
                    data = response.json()
                    content = data["choices"][0]["message"]["content"].strip()
                else:
                    # Fallback for OpenAI if openai module is available
                    try:
                        import openai
                        client = openai.OpenAI(api_key=api_key)
                        response = client.chat.completions.create(
                            model="gpt-4o",
                            messages=[{"role": "user", "content": prompt}],
                            response_format={"type": "json_object"},
                            temperature=0.0
                        )
                        content = response.choices[0].message.content
                    except ImportError:
                        # Fallback if openai not installed
                        raise ValueError("No local_api_base provided and openai module not available")
                
                result = _extract_json_object(content)
                label = result.get("label", result.get("concept", "Unknown concept"))
                confidence = float(result.get("confidence", 0.0))
            except Exception as e:
                print(f"API Error on feature {feat_idx}: {e}")
                label = "API Error"
                confidence = 0.0
        else:
            # Fallback MOCK LLM CALL
            label = "Mock domain concept"
            confidence = 0.85 # Assume MP features are highly monosemantic
        
        results[int(feat_idx)] = {
            "label": label,
            "confidence": confidence
        }
    
    if len(results) > 0:
        avg_confidence = sum(r["confidence"] for r in results.values()) / len(results)
    else:
        avg_confidence = 0.0

    print(f"\n--- Evaluation Complete ---")
    print(f"Average MP Domain Feature Confidence: {avg_confidence:.2f}")
    
    # Check against the Illusion
    illusions = [k for k, v in results.items() if v['confidence'] < 0.3]
    print(f"Features falling completely to the Illusion of Interpretability (Score < 0.3): {len(illusions)}")
    
    os.makedirs(os.path.dirname(out_file), exist_ok=True)
    with open(out_file, 'w') as f:
        json.dump(results, f, indent=4)
    print(f"LLM Annotations saved to {out_file}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", type=str, required=True, help="Input JSON report from apply_mp_threshold.py")
    parser.add_argument("--f_acts", type=str, required=True, help="Path to the sparse activations .pt file")
    parser.add_argument("--data", type=str, default="placeholder", help="Original dataset path (for extracting context)")
    parser.add_argument("--out", type=str, required=True, help="Output JSON for LLM scores")
    parser.add_argument("--local_api_base", type=str, default=None, help="Local vLLM server base URL (e.g. http://localhost:8000/v1)")
    parser.add_argument("--local_model_id", type=str, default="meta-llama/Meta-Llama-3-70B-Instruct", help="Local model ID")
    
    args = parser.parse_args()
    test_illusion_of_interpretability(args.report, args.f_acts, args.data, args.out, args.local_api_base, args.local_model_id)

